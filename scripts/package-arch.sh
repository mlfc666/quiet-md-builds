#!/usr/bin/env bash
# Build an Arch Linux package (`.pkg.tar.zst`) for Quiet.md.
#
#   scripts/package-arch.sh
#
# An Arch package is a zstd-compressed tar holding the payload plus a `.PKGINFO`
# file at its root; pacman needs nothing else. That means it can be assembled on
# any Linux host (CI builds it on Ubuntu) and still installs with `pacman -U` on
# Arch, Manjaro, EndeavourOS, CachyOS, …
#
# Dependency names are Arch's, not Debian's, so they are listed explicitly:
# there is no ldd -> package database on a non-Arch build host.
set -euo pipefail
export LC_ALL=C
cd "$(dirname "$0")/.."

[[ $(uname -s) == Linux ]] || { echo 'Build this package on Linux.' >&2; exit 1; }
command -v zstd >/dev/null || { echo 'Install zstd.' >&2; exit 1; }

version=$(sed -n 's/^version = "\([^"]*\)"/\1/p' Cargo.toml | head -1)
pkgrel=1
case $(uname -m) in
  x86_64)        pkgarch=x86_64 ;;
  aarch64|arm64) pkgarch=aarch64 ;;
  *) echo "unsupported machine: $(uname -m)" >&2; exit 1 ;;
esac

binary=${BIN:-${CARGO_TARGET_DIR:-target}/release/quiet_md}
[[ -x $binary ]] || { echo "missing $binary; run: cargo build --release" >&2; exit 1; }

outdir=dist/linux
mkdir -p "$outdir"

stage=$(mktemp -d); trap 'rm -rf "$stage"' EXIT
install -d "$stage/usr/bin" "$stage/usr/share/applications" \
          "$stage/usr/share/icons/hicolor/512x512/apps" "$stage/usr/share/licenses/quiet-md"

install -m755 "$binary" "$stage/usr/bin/quiet_md"
ln -s quiet_md "$stage/usr/bin/quiet-md"
install -m644 packaging/linux/com.s1dashu.quietmd.desktop "$stage/usr/share/applications/"
# The icon is a build-time nicety: fall back to the checked-in 1024px PNG when
# ImageMagick is absent instead of failing the whole package.
icon=assets/branding/app-icon.png
if command -v magick >/dev/null 2>&1; then
  magick "$icon" -resize 512x512 "$stage/usr/share/icons/hicolor/512x512/apps/com.s1dashu.quietmd.png"
elif command -v convert >/dev/null 2>&1; then
  convert "$icon" -resize 512x512 "$stage/usr/share/icons/hicolor/512x512/apps/com.s1dashu.quietmd.png"
else
  echo 'warning: ImageMagick missing, shipping the icon at its original size' >&2
  install -m644 "$icon" "$stage/usr/share/icons/hicolor/512x512/apps/com.s1dashu.quietmd.png"
fi
install -m644 LICENSE "$stage/usr/share/licenses/quiet-md/LICENSE"

size=$(du -sb "$stage" | cut -f1)
cat > "$stage/.PKGINFO" <<EOF
# Generated by scripts/package-arch.sh
pkgname = quiet-md
pkgbase = quiet-md
pkgver = ${version}-${pkgrel}
pkgdesc = Fast, local-first rich-text notes app drawn with GPUI
url = https://quiet.md
builddate = $(date -u +%s)
packager = quiet-md-builds <noreply@github.com>
size = ${size}
arch = ${pkgarch}
license = MIT
depend = fontconfig
depend = freetype2
depend = libxkbcommon
depend = libxkbcommon-x11
depend = libxcb
depend = libx11
depend = wayland
depend = vulkan-icd-loader
depend = openssl
depend = zlib
depend = bzip2
depend = libpng
depend = brotli
optdepend = vulkan-swrast: software Vulkan fallback for VMs
optdepend = noto-fonts: Latin/CJK glyph coverage
optdepend = noto-fonts-cjk: CJK glyph coverage
EOF

out="$outdir/quiet-md-${version}-${pkgrel}-${pkgarch}.pkg.tar.zst"
tar --zstd -cf "$out" -C "$stage" .PKGINFO usr
(cd "$outdir" && sha256sum "$(basename "$out")" > "$(basename "$out").sha256")
echo "built $out ($(du -h "$out" | cut -f1))"
